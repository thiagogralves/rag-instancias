export function extraDropId(itemId: number) {
  return `x-${Math.round(itemId)}`
}

export function parseExtraItemId(dropId: string) {
  const match = /^x-(\d+)$/.exec(dropId)
  return match ? Number(match[1]) : undefined
}

/** Prefer curated map; fall back to an explicit id from data.ts when present. */
